def fixture = new File(basedir, '../generate-basic').canonicalFile
def stamp = 1000000000000L

def files = []
['src/main/java', 'src/test/java'].collect { new File(fixture, it) }.findAll { it.isDirectory() }.each { dir ->
    dir.eachFileRecurse(groovy.io.FileType.FILES) { files << it }
}
assert files.size() >= 10 : "expected the first run's sources under $fixture, found $files"

def rewritten = files.findAll { it.lastModified() != stamp }.collect { fixture.toPath().relativize(it.toPath()).toString() }.sort()
assert rewritten.isEmpty() : "second run rewrote files generated by the first run: $rewritten"

assert new File(fixture, 'target/classes/org/openapitools/api/ProductController.class').isFile() : 'second run did not compile'

def log = new File(basedir, 'build.log').text
assert log.contains('--- allcrud-generator:') && log.contains(':generate ') : 'expected the generate goal'
assert (log =~ /--- compiler:[^ ]+:compile/).find() : 'expected the compile goal'

return true
